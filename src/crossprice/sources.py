"""The retailer register: every candidate, kept or dropped, with its recon evidence.

    python -m crossprice.sources --vertical coffee-equipment \\
        --overlap checks/analysis/overlap.json checks/results/recon-*/recon.json > docs/sources.md
    python -m crossprice.sources --vertical coffee-equipment --retailers-yml \\
        checks/results/recon-*/recon.json > config/retailers.yml

Drop rules (docs/decisions.md D-006): a challenge or block in any recon run, a
429 retry in any recon run, a robots.txt that disallows a path we use, or a
failed verdict in the retailer's latest recon. The chosen vertical's passing
retailers are kept; every other candidate is listed with the reason.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

# D-015: 16 pages of 250 products.
MAX_PRODUCTS = 4000
# Reasons that drop a retailer whatever later runs show (D-006). A 429 alone is not
# one of them since D-016: it must be followed by a clean re-test.
STICKY = ("blocked or challenged", "robots disallows")
THROTTLED = "needed 429 retries"


@dataclass
class Entry:
    store_id: str
    store: str
    vertical: str
    domain: str
    host: str = ""
    runs: list[str] = field(default_factory=list)
    sticky: list[str] = field(default_factory=list)
    latest: dict[str, Any] = field(default_factory=dict)

    @property
    def reasons(self) -> list[str]:
        out = list(dict.fromkeys(self.sticky))
        if not self.latest.get("passed"):
            out += [r for r in self.latest.get("fail_reasons") or [] if r not in out]
        size = self.latest.get("meta_products")
        if isinstance(size, int) and size > MAX_PRODUCTS:
            out.append(f"catalog too large for the daily budget ({size:,} products)")
        return out

    @property
    def passed(self) -> bool:
        return not self.reasons


def collect(paths: list[Path]) -> dict[str, Entry]:
    entries: dict[str, Entry] = {}
    for path in sorted(paths, key=lambda p: p.parent.name):
        run_id = path.parent.name
        for r in json.loads(path.read_text(encoding="utf-8"))["results"]:
            e = entries.get(r["store_id"]) or Entry(
                r["store_id"], r["store"], r["vertical"], r["domain"]
            )
            entries[r["store_id"]] = e
            e.runs.append(run_id)
            e.host = r.get("host") or e.host
            reasons = r.get("fail_reasons") or []
            throttled_only = any(x.startswith(THROTTLED) for x in reasons)
            for reason in reasons:
                # "blocked mid-recon" after a 429 is the throttle, not a challenge.
                if reason.startswith(STICKY) or (
                    reason.startswith("blocked mid-recon") and not throttled_only
                ):
                    e.sticky.append(f"{reason} ({run_id})")
            # "not checked (run halted)" says nothing about the retailer: keep the older result.
            if r.get("fail_reasons") != ["not checked (run halted)"] or not e.latest:
                e.latest = r | {"run_id": run_id}
    return entries


def load_reviews(path: Path) -> dict[str, list[str]]:
    if not path.exists():
        return {}
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    out: dict[str, list[str]] = defaultdict(list)
    for item in raw.get("reviews") or []:
        out[item["store"]].extend(item["titles"])
    return out


def retailers_yml(entries: dict[str, Entry], vertical: str, reviews: dict[str, list[str]]) -> str:
    kept = sorted(
        (e for e in entries.values() if e.vertical == vertical and e.passed),
        key=lambda e: e.store_id,
    )
    data = {
        "retailers": [
            {
                "id": e.store_id,
                "name": e.store,
                "vertical": e.vertical,
                "host": e.host or e.domain,
                **({"screen_reviewed": reviews[e.store]} if e.store in reviews else {}),
            }
            for e in kept
        ]
    }
    head = (
        "# Generated by python -m crossprice.sources from the recon evidence in\n"
        "# checks/results/ (docs/sources.md lists every candidate and why it was kept\n"
        "# or dropped). Do not edit by hand.\n"
    )
    return head + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)


def _pct(v: Any) -> str:
    return "-" if v is None else f"{v:.0%}"


def sources_md(entries: dict[str, Entry], vertical: str, overlap: dict[str, Any] | None) -> str:
    by_v: dict[str, list[Entry]] = defaultdict(list)
    for e in entries.values():
        by_v[e.vertical].append(e)
    ov = (overlap or {}).get(vertical, {}).get("retailers", {})
    kept = [e for e in by_v[vertical] if e.passed]
    lines = [
        "# Sources",
        "",
        f"Chosen vertical: **{vertical}** ({len(kept)} retailers). Rules: D-002 and D-006 in",
        "[decisions.md](decisions.md). Evidence: the recon runs in `checks/results/` named",
        "in each row. Generated by `python -m crossprice.sources`.",
        "",
        "## Compared retailers",
        "",
        "| retailer | host | products | overlap | GTIN (sampled variants) | recon runs |",
        "|---|---|---:|---:|---:|---|",
    ]
    for e in sorted(kept, key=lambda x: x.store.lower()):
        o = ov.get(e.store_id, {})
        g = f"{o.get('sampled_with_gtin')}/{o.get('sampled_variants')}" if o else "-"
        lines.append(
            f"| {e.store} | `{e.host or e.domain}` | {o.get('products', '-')} "
            f"| {_pct(o.get('overlap_share'))} | {g} | {', '.join(dict.fromkeys(e.runs))} |"
        )
    lines += ["", "## Not compared", ""]
    for v in sorted(by_v):
        rows = [e for e in by_v[v] if not (v == vertical and e.passed)]
        if not rows:
            continue
        lines += [
            f"### {v}",
            "",
            "| retailer | domain | reason | recon runs |",
            "|---|---|---|---|",
        ]
        for e in sorted(rows, key=lambda x: x.store.lower()):
            why = "; ".join(e.reasons) if e.reasons else "passed, vertical not chosen"
            lines.append(
                f"| {e.store} | `{e.domain}` | {why} | {', '.join(dict.fromkeys(e.runs))} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("recon", nargs="+", type=Path)
    p.add_argument("--vertical", required=True)
    p.add_argument("--overlap", type=Path)
    p.add_argument("--reviews", type=Path, default=Path("config/screen-review.yml"))
    p.add_argument("--retailers-yml", action="store_true")
    a = p.parse_args(argv)
    entries = collect(a.recon)
    if a.retailers_yml:
        sys.stdout.write(retailers_yml(entries, a.vertical, load_reviews(a.reviews)))
    else:
        overlap = json.loads(a.overlap.read_text()) if a.overlap else None
        sys.stdout.write(sources_md(entries, a.vertical, overlap))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
